#include "system.hpp"
#include "devices/device_factories.hpp"
#include <vector>
#include <fstream>
#include <nlohmann/json.hpp>
#include <string>
#include <string_view>
#include <filesystem>

using json = nlohmann::json;
using namespace Emulator;

std::vector<Byte> loadProgram(const std::string& filepath);
void printUsageText();
System createSystem(const std::string& confFile);

int main(int argc, char** argv) {
    if (argc < 3) {
        printUsageText();
        return 0;
    }

    std::string confFile = "";
    bool confDefined = false;

    for (int i = 1; i < argc; ++i) {
        if (confDefined)
            break;
        std::string_view arg(argv[i]);

        if (arg == "-c" || arg == "--config") {
            if (i + 1 >= argc || confDefined) {
                // Config not defined when config arg is given.
                // Or there are multiple conf args.
                printUsageText();
                return 0;
            }

            ++i;
            std::string_view confFileArg(argv[i]);
            if (confFileArg.find_first_of(".json") == confFileArg.npos) {
                // Not a json file.
                printUsageText();
                return 0;
            }

            confDefined = true;
            confFile = confFileArg;
        }

        if (arg == "-h" || arg == "--help") {
            printUsageText();
            return 0;
        }
    }

    System sys = createSystem(confFile);
    sys.powerOn();
    sys.run(std::cout);
}

// generated by an LLM
std::vector<Byte> loadProgram(const std::string& filepath) {
    // Open in binary mode and seek to the end to get the file size
    std::ifstream file(filepath, std::ios::binary | std::ios::ate);
    if (!file.is_open()) {
        throw std::runtime_error("Failed to open binary file: " + filepath);
    }

    std::streamsize size = file.tellg();
    file.seekg(0, std::ios::beg);

    std::vector<Byte> buffer(size);
    if (file.read(reinterpret_cast<char*>(buffer.data()), size)) {
        return buffer;
    }

    throw std::runtime_error("Failed to read binary file: " + filepath);
}

void printUsageText() {
    std::cout << "Usage: mos6502 [args]\n"
        << "Args:\n"
        << "\t-c / --config <conf.json> | Set the system config file.\n"
        << "\t-h / --help               | Display this usage text.\n";
}

System createSystem(const std::string& confFile) {
    std::vector<std::shared_ptr<Device>> deviceList;
    std::shared_ptr<Display> display;


    std::ifstream conf(confFile);
    if (!conf.is_open()) {
        std::cerr << "Failed to open conf file \"" << confFile << "\"\n";
        exit(1);
    }
    std::filesystem::path confDir(std::filesystem::path(confFile).parent_path());
    json data = json::parse(conf);

    bool displayDefined = false;
    for (auto d : data["devices"]) {
        std::string dtype = d["type"];
        if (dtype == "ram") {
            deviceList.push_back(DeviceFactory::createRamDevice(d["start_page"], d["size_in_pages"]));
        } else if (dtype == "rom") {
            auto initData = loadProgram(confDir / std::string(d["data"]));
            deviceList.push_back(DeviceFactory::createRomDevice(d["start_page"], d["size_in_pages"], initData));
        } else if (dtype == "system_interface") {
            deviceList.push_back(DeviceFactory::createSystemInterfaceDevice(d["start_page"]));
        } else if (dtype == "ram_bank") {
            int address_width = d["address_width"];
            switch(address_width) {
                case 16:
                    deviceList.push_back(DeviceFactory::create16BitRamBankDevice(d["start_page"])); break;
                case 24:
                    deviceList.push_back(DeviceFactory::create24BitRamBankDevice(d["start_page"])); break;
                case 32:
                    deviceList.push_back(DeviceFactory::create32BitRamBankDevice(d["start_page"])); break;
                default:
                    std::cerr << "Invalid address width.\n"
                              << "Valid address widths: 16 | 24 | 32\n";
                    exit(1);
            }
        } else if (dtype == "rom_bank") {
            auto initData = loadProgram(confDir / std::string(d["data"]));
            int address_width = d["address_width"];
            switch(address_width) {
                case 16:
                    deviceList.push_back(DeviceFactory::create16BitRomBankDevice(d["start_page"], initData)); break;
                case 24:
                    deviceList.push_back(DeviceFactory::create24BitRomBankDevice(d["start_page"], initData)); break;
                case 32:
                    deviceList.push_back(DeviceFactory::create32BitRomBankDevice(d["start_page"], initData)); break;
                default:
                    std::cerr << "Invalid address width.\n"
                              << "Valid address widths: 16 | 24 | 32\n";
                    exit(1);
            }

        } else if (dtype == "display") {
            if (displayDefined)
                continue;
            std::string subtype = d["subtype"];
            Byte start_page = d["start_page"];
            size_t width = d["width"];
            size_t height = d["height"];
            Display::RefreshRate hz;
            int hz_int = d["refresh_rate"];
            switch(hz_int) {
                case 1:
                    hz = Display::RefreshRate::ONE; break;
                case 2:
                    hz = Display::RefreshRate::TWO; break;
                case 4:
                    hz = Display::RefreshRate::FOUR; break;
                case 5:
                    hz = Display::RefreshRate::FIVE; break;
                case 8:
                    hz = Display::RefreshRate::EIGHT; break;
                case 10:
                    hz = Display::RefreshRate::TEN; break;
                case 20:
                    hz = Display::RefreshRate::TWENTY; break;
                case 25:
                    hz = Display::RefreshRate::TWENTY_FIVE; break;
                default:
                    std::cerr << "Invalid display refresh rate.\n"
                              << "Valid refresh rates: 1 | 2 | 4 | 5 | 8 | 10 | 20 | 25\n";
                    exit(1);
            }

            if (subtype == "pixel") {
                display = DeviceFactory::createPixelDisplayDevice(start_page, width, height, hz);
            } else if (subtype == "ascii") {
                display = DeviceFactory::createAsciiDisplayDevice(start_page, width, height, hz);
            }

            deviceList.push_back(display);
            displayDefined = true;
        }
    }

    return System(deviceList, display);
}
